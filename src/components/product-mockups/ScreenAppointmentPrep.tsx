"use client";

import React, { useState } from "react";
import {
  Calendar,
  HelpCircle,
  FileText,
  Pill,
  Activity,
  CheckSquare,
  Square,
  Share2,
  Printer,
  Sparkles,
} from "lucide-react";

export interface ScreenAppointmentPrepProps {
  className?: string;
}

export function ScreenAppointmentPrep({
  className = "",
}: ScreenAppointmentPrepProps) {
  // Checkbox state for interactive feel
  const [checkedQuestions, setCheckedQuestions] = useState<Record<number, boolean>>({
    0: true,
  });
  const [checkedDocs, setCheckedDocs] = useState<Record<number, boolean>>({
    0: true,
    1: true,
  });

  function toggleQuestion(idx: number) {
    setCheckedQuestions((prev) => ({ ...prev, [idx]: !prev[idx] }));
  }

  function toggleDoc(idx: number) {
    setCheckedDocs((prev) => ({ ...prev, [idx]: !prev[idx] }));
  }

  const QUESTIONS = [
    "What specific heart rate thresholds should prompt me to contact your triage desk?",
    "Could my mild evening palpitations be connected to caffeine timing or current medication?",
    "Do you recommend a 30-day Holter monitor patch or an echocardiogram first?",
    "Are there any changes I should make to my daily exercise and cardio routine?",
  ];

  const DOCUMENTS = [
    { label: "Valid Government Photo ID (Driver's License)", status: "Ready" },
    { label: "UnitedHealthcare Choice Plus Insurance Card", status: "Ready" },
    { label: "CareLoop Pre-visit Clinical Summary Packet", status: "Staged on Phone" },
    { label: "Recent Blood Chemistry Panel (July 2026)", status: "Electronically Transferred" },
  ];

  const MEDICATIONS = [
    { name: "Lisinopril", dose: "10mg daily", timing: "Every morning with water", purpose: "Blood pressure regulation" },
    { name: "Atorvastatin", dose: "20mg daily", timing: "Bedtime", purpose: "Cholesterol maintenance" },
    { name: "CoQ10 Supplement", dose: "100mg daily", timing: "With lunch", purpose: "Cardiovascular cellular support" },
  ];

  const SYMPTOMS = [
    { date: "Nov 14", desc: "Wearable sensor recorded resting pulse dip to 54 bpm while sleeping" },
    { date: "Nov 8", desc: "Mild chest flutter lasting ~30 seconds after brisk uphill stairs" },
    { date: "Nov 2", desc: "Lightheadedness after standing up quickly following morning workout" },
  ];

  return (
    <div className={`space-y-6 bg-[#FAF8F5] p-4 sm:p-6 text-[#191716] ${className}`}>
      {/* Top Header & Context */}
      <div className="rounded-2xl border border-[#E2DDD5] bg-white p-5 shadow-soft flex flex-col sm:flex-row sm:items-center sm:justify-between gap-4">
        <div>
          <div className="flex items-center gap-2">
            <span className="inline-flex items-center gap-1.5 rounded-full bg-[#EBF5F3] px-3 py-0.5 text-xs font-bold text-[#0E6156]">
              <Sparkles className="h-3 w-3" />
              Pre-Visit Briefing
            </span>
            <span className="text-xs text-[#8A8279]">Generated by CareLoop</span>
          </div>
          <h2 className="text-2xl sm:text-3xl font-extrabold text-[#191716] mt-1.5 tracking-tight">
            Appointment Prep
          </h2>
          <p className="text-xs sm:text-sm text-[#5C5650] mt-0.5">
            Everything you need organized so you can walk into your consultation confident and prepared.
          </p>
        </div>

        <div className="flex items-center gap-2 self-start sm:self-auto">
          <button
            type="button"
            className="inline-flex items-center gap-1.5 rounded-xl border border-[#E2DDD5] bg-white px-3 py-2 text-xs font-semibold text-[#5C5650] hover:bg-[#FAF8F5] transition-colors"
          >
            <Printer className="h-3.5 w-3.5" />
            <span>Print Packet</span>
          </button>
          <button
            type="button"
            className="inline-flex items-center gap-1.5 rounded-xl bg-[#0E6156] px-3.5 py-2 text-xs font-bold text-white hover:bg-[#09473F] transition-colors"
          >
            <Share2 className="h-3.5 w-3.5" />
            <span>Share with Doctor</span>
          </button>
        </div>
      </div>

      {/* SECTION 1: APPOINTMENT DETAILS */}
      <div className="rounded-2xl border border-[#E2DDD5] bg-white p-5 shadow-soft space-y-4">
        <div className="flex items-center justify-between border-b border-[#E2DDD5]/70 pb-3">
          <div className="flex items-center gap-2">
            <Calendar className="h-4 w-4 text-[#0E6156]" />
            <h3 className="text-base font-bold text-[#191716]">Appointment Details</h3>
          </div>
          <span className="text-xs font-semibold text-[#0E6156] bg-teal-50 px-2.5 py-0.5 rounded-full border border-teal-200">
            Confirmed Slot
          </span>
        </div>

        <div className="grid grid-cols-1 sm:grid-cols-3 gap-4 text-xs">
          <div className="rounded-xl bg-[#FAF8F5] p-3.5 border border-[#E2DDD5]/70">
            <span className="text-[#8A8279] block mb-1 font-semibold">Specialist &amp; Clinic</span>
            <div className="font-bold text-[#191716] text-sm">Dr. Sarah Lin, MD</div>
            <div className="text-[#5C5650] mt-0.5">Bay Area Cardiovascular Specialists</div>
          </div>

          <div className="rounded-xl bg-[#FAF8F5] p-3.5 border border-[#E2DDD5]/70">
            <span className="text-[#8A8279] block mb-1 font-semibold">Date &amp; Arrival Window</span>
            <div className="font-bold text-[#191716] text-sm">Thursday, Nov 19 at 10:15 AM</div>
            <div className="text-[#0E6156] font-medium mt-0.5">Please arrive by 10:00 AM for check-in</div>
          </div>

          <div className="rounded-xl bg-[#FAF8F5] p-3.5 border border-[#E2DDD5]/70">
            <span className="text-[#8A8279] block mb-1 font-semibold">Location &amp; Parking</span>
            <div className="font-bold text-[#191716] text-sm">450 Sutter St, Suite 800</div>
            <div className="text-[#5C5650] mt-0.5">Underground garage validated at front desk</div>
          </div>
        </div>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-12 gap-5">
        {/* SECTION 2: QUESTIONS TO ASK */}
        <div className="lg:col-span-6 rounded-2xl border border-[#E2DDD5] bg-white p-5 shadow-soft space-y-4">
          <div className="flex items-center justify-between border-b border-[#E2DDD5]/70 pb-3">
            <div className="flex items-center gap-2">
              <HelpCircle className="h-4 w-4 text-[#0E6156]" />
              <h3 className="text-base font-bold text-[#191716]">Questions to Ask</h3>
            </div>
            <span className="text-[11px] text-[#8A8279]">Tap to mark discussed</span>
          </div>

          <div className="space-y-2.5">
            {QUESTIONS.map((q, idx) => {
              const isChecked = !!checkedQuestions[idx];
              return (
                <div
                  key={idx}
                  onClick={() => toggleQuestion(idx)}
                  className={`cursor-pointer rounded-xl p-3 border text-xs transition-all flex items-start gap-2.5 ${
                    isChecked
                      ? "bg-[#EBF5F3]/50 border-teal-200 text-[#0E6156]"
                      : "bg-[#FAF8F5] border-[#E2DDD5] text-[#191716] hover:bg-white"
                  }`}
                >
                  <button type="button" className="shrink-0 mt-0.5">
                    {isChecked ? (
                      <CheckSquare className="h-4 w-4 text-[#0E6156]" />
                    ) : (
                      <Square className="h-4 w-4 text-[#8A8279]" />
                    )}
                  </button>
                  <span className={`leading-relaxed ${isChecked ? "line-through opacity-75" : ""}`}>
                    {q}
                  </span>
                </div>
              );
            })}
          </div>
        </div>

        {/* SECTION 3: DOCUMENTS TO BRING */}
        <div className="lg:col-span-6 rounded-2xl border border-[#E2DDD5] bg-white p-5 shadow-soft space-y-4">
          <div className="flex items-center justify-between border-b border-[#E2DDD5]/70 pb-3">
            <div className="flex items-center gap-2">
              <FileText className="h-4 w-4 text-[#1E6091]" />
              <h3 className="text-base font-bold text-[#191716]">Documents to Bring</h3>
            </div>
            <span className="text-[11px] text-[#8A8279]">Pre-verified checklist</span>
          </div>

          <div className="space-y-2.5">
            {DOCUMENTS.map((doc, idx) => {
              const isChecked = !!checkedDocs[idx];
              return (
                <div
                  key={idx}
                  onClick={() => toggleDoc(idx)}
                  className="cursor-pointer rounded-xl p-3 border border-[#E2DDD5] bg-[#FAF8F5] hover:bg-white text-xs transition-all flex items-center justify-between gap-3"
                >
                  <div className="flex items-center gap-2.5">
                    <button type="button">
                      {isChecked ? (
                        <CheckSquare className="h-4 w-4 text-[#0E6156]" />
                      ) : (
                        <Square className="h-4 w-4 text-[#8A8279]" />
                      )}
                    </button>
                    <span className="font-medium text-[#191716]">{doc.label}</span>
                  </div>
                  <span className="text-[10px] font-semibold text-[#0E6156] bg-teal-50 px-2 py-0.5 rounded-full border border-teal-200 shrink-0">
                    {doc.status}
                  </span>
                </div>
              );
            })}
          </div>
        </div>

        {/* SECTION 4: MEDICATIONS TO REVIEW */}
        <div className="lg:col-span-6 rounded-2xl border border-[#E2DDD5] bg-white p-5 shadow-soft space-y-4">
          <div className="flex items-center justify-between border-b border-[#E2DDD5]/70 pb-3">
            <div className="flex items-center gap-2">
              <Pill className="h-4 w-4 text-[#C87D2A]" />
              <h3 className="text-base font-bold text-[#191716]">Medications to Review</h3>
            </div>
            <span className="text-[11px] text-[#8A8279]">Current regimen</span>
          </div>

          <div className="space-y-2.5">
            {MEDICATIONS.map((med, idx) => (
              <div key={idx} className="rounded-xl bg-[#FAF8F5] p-3 border border-[#E2DDD5]/70 text-xs">
                <div className="flex items-center justify-between font-bold text-[#191716]">
                  <span>{med.name} ({med.dose})</span>
                  <span className="text-[11px] font-normal text-[#5C5650]">{med.timing}</span>
                </div>
                <div className="text-[11px] text-[#8A8279] mt-0.5">Purpose: {med.purpose}</div>
              </div>
            ))}
          </div>
        </div>

        {/* SECTION 5: SYMPTOMS TO MENTION */}
        <div className="lg:col-span-6 rounded-2xl border border-[#E2DDD5] bg-white p-5 shadow-soft space-y-4">
          <div className="flex items-center justify-between border-b border-[#E2DDD5]/70 pb-3">
            <div className="flex items-center gap-2">
              <Activity className="h-4 w-4 text-rose-600" />
              <h3 className="text-base font-bold text-[#191716]">Symptoms to Mention</h3>
            </div>
            <span className="text-[11px] text-[#8A8279]">Logged in CareLoop</span>
          </div>

          <div className="space-y-2.5">
            {SYMPTOMS.map((sym, idx) => (
              <div key={idx} className="rounded-xl bg-[#FAF8F5] p-3 border border-[#E2DDD5]/70 text-xs flex items-start gap-3">
                <span className="font-bold text-rose-700 bg-rose-50 px-2 py-0.5 rounded-md border border-rose-200 shrink-0 text-[11px]">
                  {sym.date}
                </span>
                <span className="text-[#191716] leading-relaxed">{sym.desc}</span>
              </div>
            ))}
          </div>
        </div>
      </div>
    </div>
  );
}
